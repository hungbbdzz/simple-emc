#!/usr/bin/env python3
"""Reports remaining Forge/NeoForge source duplication after shared-source extraction."""

from __future__ import annotations

import difflib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORGE = ROOT / "forge-1.20.1" / "src" / "main" / "java"
NEOFORGE = ROOT / "neoforge-1.21.1" / "src" / "main" / "java"
SHARED = ROOT / "common-gameplay" / "src" / "main" / "java"
OUTPUT = ROOT / "build" / "reports" / "source-duplication-audit.txt"


def java_map(root: Path) -> dict[Path, Path]:
    return {path.relative_to(root): path for path in root.rglob("*.java")}


def lines(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def main() -> None:
    forge = java_map(FORGE)
    neo = java_map(NEOFORGE)
    shared = java_map(SHARED)
    same_paths = sorted(set(forge) & set(neo))

    comparisons: list[tuple[float, Path, int, int]] = []
    exact: list[Path] = []
    for relative in same_paths:
        left = forge[relative].read_text(encoding="utf-8").splitlines()
        right = neo[relative].read_text(encoding="utf-8").splitlines()
        ratio = difflib.SequenceMatcher(None, left, right).ratio()
        comparisons.append((ratio, relative, len(left), len(right)))
        if left == right:
            exact.append(relative)

    near = sorted((entry for entry in comparisons if entry[0] >= 0.90), reverse=True)
    medium = sorted((entry for entry in comparisons if 0.70 <= entry[0] < 0.90), reverse=True)
    divergent = sorted((entry for entry in comparisons if entry[0] < 0.70), reverse=True)
    weighted_denominator = sum(max(a, b) for _, _, a, b in comparisons)
    weighted_similarity = (
        sum(ratio * max(a, b) for ratio, _, a, b in comparisons) / weighted_denominator
        if weighted_denominator else 1.0
    )

    rows = [
        "# Refactor Duplication Audit",
        "",
        "Generated by `scripts/audit_source_duplication.py`.",
        "",
        "## Current source split",
        "",
        "| Source root | Java classes | Lines |",
        "|---|---:|---:|",
        f"| `common-gameplay` | {len(shared)} | {sum(lines(p) for p in shared.values()):,} |",
        f"| Forge-only | {len(forge)} | {sum(lines(p) for p in forge.values()):,} |",
        f"| NeoForge-only | {len(neo)} | {sum(lines(p) for p in neo.values()):,} |",
        "",
        "## Remaining overlap",
        "",
        f"- Same relative class paths still present in both loaders: **{len(same_paths)}**",
        f"- Exact duplicates remaining: **{len(exact)}**",
        f"- Line-weighted similarity across same-path classes: **{weighted_similarity * 100:.1f}%**",
        f"- Candidates at or above 90% similarity: **{len(near)}**",
        f"- Candidates from 70% to 89.9% similarity: **{len(medium)}**",
        f"- Loader-divergent classes below 70% similarity: **{len(divergent)}**",
        "",
        "## Next extraction candidates",
        "",
        "These classes are similar enough to inspect next, but were not moved automatically because their differences may encode Minecraft-version or loader behavior.",
        "",
        "| Similarity | Class | Forge lines | NeoForge lines |",
        "|---:|---|---:|---:|",
    ]
    for ratio, relative, forge_lines, neo_lines in near[:30]:
        rows.append(f"| {ratio * 100:.1f}% | `{relative}` | {forge_lines} | {neo_lines} |")

    rows.extend([
        "",
        "## Policy",
        "",
        "- Exact duplicates may move directly to `common-gameplay` after the integrity guard passes.",
        "- Near-duplicates require an explicit adapter or compatibility decision; no automated merge is allowed.",
        "- Loader event registration, network codecs and version-specific APIs remain loader-side.",
        "- Gameplay balance must remain in `common-core` profiles or shared gameplay services.",
        "",
    ])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(rows), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(shared)} shared, {len(same_paths)} overlapping loader paths.")


if __name__ == "__main__":
    main()
